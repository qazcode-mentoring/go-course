package main

import "fmt"

// DoubleValue принимает число и возвращает удвоенное значение
// Оригинальное значение НЕ изменяется
func DoubleValue(n int) int {
	// TODO: реализуй функцию
	return n * 2
}

// DoublePointer принимает указатель и удваивает значение напрямую
// Оригинальное значение ИЗМЕНЯЕТСЯ
func DoublePointer(n *int) {
	// TODO: реализуй функцию
	*n = *n * 2
}

func main() {
	// Демонстрация передачи по значению
	fmt.Println("=== Передача по значению ===")
	a := 5
	b := DoubleValue(a)
	fmt.Printf("a = %d (не изменилось)\n", a)
	fmt.Printf("b = %d (результат функции)\n", b)

	// Демонстрация передачи по указателю
	fmt.Println("\n=== Передача по указателю ===")
	c := 5
	fmt.Printf("c до вызова: %d\n", c)
	DoublePointer(&c)
	fmt.Printf("c после вызова: %d\n", c)
}

